  function num(x, d) {
    const s = Number(x).toFixed(d);
    let [i, f] = s.split(".");
    if (i.replace("-", "").length > 4) i = i.replace(/\B(?=(\d{3})+(?!\d))/g, " ");
    return f ? i + "," + f : i;
  }
  // разумная точность: 1234 · 62,5 · 4,2 · 0,15
  function nice(x) {
    const a = Math.abs(x);
    const d = a >= 100 ? 0 : a >= 1 ? 1 : a >= 0.1 ? 2 : 3;
    return num(x, d).replace(/(,\d*?)0+$/, "$1").replace(/,$/, "");
  }
  function years(v) {
    if (v < 1) return "меньше года";
    const r = Number(v.toFixed(v < 10 ? 1 : 0));
    if (!Number.isInteger(r)) return `≈ ${num(r, 1)} года`;
    const n10 = r % 10, n100 = r % 100;
    const w = n10 === 1 && n100 !== 11 ? "год" : n10 >= 2 && n10 <= 4 && (n100 < 12 || n100 > 14) ? "года" : "лет";
    return `≈ ${num(r, 0)} ${w}`;
  }

